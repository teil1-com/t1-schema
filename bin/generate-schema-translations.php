<?php
/**
 * Generate an extractable gettext catalog for Schema.org display metadata.
 *
 * The schema JSON remains the canonical machine-readable registry. This script
 * emits explicit _x() calls so WordPress.org can discover its labels and
 * descriptions while runtime identifiers remain unchanged.
 *
 * Usage:
 *   php bin/generate-schema-translations.php
 */

declare( strict_types=1 );

$root        = dirname( __DIR__ );
$source_file = $root . '/data/schema-types.json';
$target_file = $root . '/includes/SchemaTypeTranslations.php';

$source = file_get_contents( $source_file );
if ( false === $source ) {
    fwrite( STDERR, "Unable to read {$source_file}\n" );
    exit( 1 );
}

$types = json_decode( $source, true, 512, JSON_THROW_ON_ERROR );
if ( ! is_array( $types ) ) {
    fwrite( STDERR, "Schema registry must decode to an array.\n" );
    exit( 1 );
}

$labels       = [];
$descriptions = [];

foreach ( $types as $definition ) {
    if ( ! empty( $definition['label'] ) ) {
        $labels[ $definition['label'] ] = true;
    }

    if ( ! empty( $definition['description'] ) ) {
        $descriptions[ $definition['description'] ] = true;
    }

    foreach ( $definition['properties'] ?? [] as $property ) {
        if ( ! empty( $property['description'] ) ) {
            $descriptions[ $property['description'] ] = true;
        }
    }
}

$labels       = array_keys( $labels );
$descriptions = array_keys( $descriptions );
sort( $labels, SORT_STRING );
sort( $descriptions, SORT_STRING );

$export = static function ( string $value ): string {
    return var_export( $value, true );
};

$lines = [
    '<?php',
    '',
    'namespace T1Schema;',
    '',
    "if ( ! defined( 'ABSPATH' ) ) {",
    '    exit;',
    '}',
    '',
    '/**',
    ' * Generated translations for Schema.org presentation metadata.',
    ' *',
    ' * Do not edit this file directly. Run:',
    ' * php bin/generate-schema-translations.php',
    ' *',
    ' * @package T1Schema',
    ' */',
    'class SchemaTypeTranslations {',
    '',
    '    /**',
    '     * Localize labels and descriptions without changing machine identifiers.',
    '     *',
    '     * @param array<string, array> $types Canonical schema definitions.',
    '     * @return array<string, array> Localized definitions.',
    '     */',
    '    public static function localize( array $types ): array {',
    '        $labels       = self::labels();',
    '        $descriptions = self::descriptions();',
    '',
    '        foreach ( $types as &$definition ) {',
    "            if ( isset( \$definition['label'], \$labels[ \$definition['label'] ] ) ) {",
    "                \$definition['label'] = \$labels[ \$definition['label'] ];",
    '            }',
    '',
    "            if ( isset( \$definition['description'], \$descriptions[ \$definition['description'] ] ) ) {",
    "                \$definition['description'] = \$descriptions[ \$definition['description'] ];",
    '            }',
    '',
    "            foreach ( \$definition['properties'] ?? [] as &\$property ) {",
    "                if ( isset( \$property['description'], \$descriptions[ \$property['description'] ] ) ) {",
    "                    \$property['description'] = \$descriptions[ \$property['description'] ];",
    '                }',
    '            }',
    '            unset( $property );',
    '        }',
    '        unset( $definition );',
    '',
    '        return $types;',
    '    }',
    '',
    '    /** @return array<string, string> */',
    '    private static function labels(): array {',
    '        return [',
];

foreach ( $labels as $label ) {
    $value   = $export( $label );
    $lines[] = "            {$value} => _x( {$value}, 'Schema.org type label', 'teil1-schema-manager' ),";
}

$lines[] = '        ];';
$lines[] = '    }';
$lines[] = '';
$lines[] = '    /** @return array<string, string> */';
$lines[] = '    private static function descriptions(): array {';
$lines[] = '        return [';

foreach ( $descriptions as $description ) {
    $value   = $export( $description );
    $lines[] = "            {$value} => _x( {$value}, 'Schema.org type or property description', 'teil1-schema-manager' ),";
}

$lines[] = '        ];';
$lines[] = '    }';
$lines[] = '}';
$lines[] = '';

$result = file_put_contents( $target_file, implode( "\n", $lines ) );
if ( false === $result ) {
    fwrite( STDERR, "Unable to write {$target_file}\n" );
    exit( 1 );
}

printf(
    "Generated %s with %d labels and %d unique descriptions.\n",
    $target_file,
    count( $labels ),
    count( $descriptions )
);
